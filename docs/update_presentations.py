# Avoid replacing generic standalone word "Ученик" in arbitrary contexts; targeted replacements above carry the product meaning.
for src in sorted(SRC.glob('*.pptx')):
    prs=Presentation(src)
    for slide in prs.slides:
        for shape in slide.shapes:
            if not getattr(shape,'has_text_frame',False): continue
            for para in shape.text_frame.paragraphs:
                for run in para.runs:
                    txt=run.text
                    for a,b in repl.items(): txt=txt.replace(a,b)
                    run.text=txt
    dst=OUT/src.name.replace('_редизайн','_версия_только_репетитор')
    prs.save(dst)
print('Updated',len(list(OUT.glob('*.pptx'))),'presentations')
